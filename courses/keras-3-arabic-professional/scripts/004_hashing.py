hash_layer = keras.layers.Hashing(
    num_bins=1024,               # حجم فضاء الهاش
    salt=1,                       # يغيّر توزيع الهاش
    output_mode="multi_hot",
)
out = hash_layer(["منتج", "جودة"])
print(out.shape)                 # النتيجة المتوقعة: (2, 1024)

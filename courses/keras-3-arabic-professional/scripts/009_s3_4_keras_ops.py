import keras

x = keras.ops.array([1.0, 2.0, 3.0])

keras.ops.softmax(x)      # تطبيع احتمالي
keras.ops.relu(x)         # تنشيط
keras.ops.matmul(x, x.T)  # ضرب مصفوفي
keras.ops.mean(x)         # متوسط
keras.ops.argmax(x)       # فهرس أكبر قيمة

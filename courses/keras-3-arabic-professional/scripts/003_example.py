import numpy as np

# مصفوفة 3×2 ومتجه طول 2
a = np.array([[1., 2.], [3., 4.], [5., 6.]])   # (3, 2)
b = np.array([10., 20.])                       # (2,)

# يعمل — لكن ليس بالطريقة التي يتوقّعها المبتدئ
print(a + b)
# [[11. 22.]
#  [13. 24.]
#  [15. 26.]]

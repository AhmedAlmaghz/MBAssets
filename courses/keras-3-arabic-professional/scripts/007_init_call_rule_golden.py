# ✗ خطأ: إنشاء طبقة داخل call
def call(self, x):
    d = keras.layers.Dense(64)   # خطأ: طبقة جديدة في كل استدعاء!
    return d(x)

# ✓ صح: أنشئها مرة واحدة في __init__
def __init__(self):
    super().__init__()
    self.d = keras.layers.Dense(64)

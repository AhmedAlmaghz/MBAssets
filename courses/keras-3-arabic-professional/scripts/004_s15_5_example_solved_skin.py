import numpy as np

counts = np.array([5200, 1800, 700, 300])
weights = counts.sum() / (len(counts) * counts)
class_weight = {i: float(w) for i, w in enumerate(weights)}
print(class_weight)   # النتيجة المتوقعة: {0: 0.577, 1: 1.667, 2: 4.286, 3: 10.0}

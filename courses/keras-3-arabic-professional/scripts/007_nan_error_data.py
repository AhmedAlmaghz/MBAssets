import numpy as np

x = np.random.rand(100, 16).astype("float32")   # بياناتك الفعلية
# تحقّق من NaN وInf
assert not np.isnan(x).any(), "x يحتوي NaN"
assert not np.isinf(x).any(), "x يحتوي Inf"

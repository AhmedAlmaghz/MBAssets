print(text[0:1])  # P (لكن كنتيجة تقطيع - الفرق دقيق لكن مهم لاحقًا)
print(text[10])   # ❌ IndexError
print(text[10:20])  # نص فارغ "" (التقطيع لا يُسبب خطأ حتى لو تجاوز الحدود!)

# مثال for: نعرف بالضبط أننا نريد 5 تكرارات
for i in range(5):
    print("مرحبا")

# مثال while: لا نعرف متى سيُدخل المستخدم كلمة المرور الصحيحة
password: str = ""
while password != "1234":
    password = input("أدخل كلمة المرور: ")

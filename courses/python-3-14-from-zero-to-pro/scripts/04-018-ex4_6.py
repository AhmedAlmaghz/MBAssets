#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
الفصل الرابع: التعامل مع النصوص (Strings)
القسم 4.6: التقطيع (Slicing): استخراج جزء من النص

المصدر: كتاب «بايثون 3.14 — من الصفر إلى الاحتراف»
الملف: 04-018-ex4_6.py
"""

text: str = "0123456789"

print(text[::2])    # 02468  (كل حرف ثانٍ)
print(text[1::2])   # 13579  (كل حرف ثانٍ، بدءًا من الفهرس 1)
print(text[::-1])   # 9876543210  (عكس النص بالكامل!)

def describe_value(value):
    match value:
        case 0:
            return "صفر"
        case int() if value > 0:
            return "رقم صحيح موجب"
        case int() if value < 0:
            return "رقم صحيح سالب"
        case str():
            return "نص"
        case _:
            return "نوع غير معروف"


#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
الفصل الخامس: الأرقام والعمليات الحسابية
القسم 5.4: أولوية العمليات (Operator Precedence)

المصدر: كتاب «بايثون 3.14 — من الصفر إلى الاحتراف»
الملف: 05-007-result.py
"""

result = 2 + 3 * 4
print(result)  # 14  ← الضرب أولاً (3*4=12)، ثم الجمع (2+12=14)

result = (2 + 3) * 4
print(result)  # 20  ← الأقواس أولاً (2+3=5)، ثم الضرب (5*4=20)

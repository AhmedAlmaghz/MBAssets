import math

print(math.sqrt(16))      # 4.0   ← الجذر التربيعي
print(math.ceil(4.1))     # 5     ← التقريب للأعلى دائمًا
print(math.floor(4.9))    # 4     ← التقريب للأسفل دائمًا
print(math.pi)             # 3.141592653589793
print(math.factorial(5))   # 120   ← المضروب (5!)

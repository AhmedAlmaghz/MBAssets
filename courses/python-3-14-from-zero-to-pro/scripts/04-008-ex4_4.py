#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
الفصل الرابع: التعامل مع النصوص (Strings)
القسم 4.4: f-strings: الطريقة الحديثة والوحيدة التي يجب أن تتعلمها

المصدر: كتاب «بايثون 3.14 — من الصفر إلى الاحتراف»
الملف: 04-008-ex4_4.py
"""

price: float = 49.99
quantity: int = 3

# حسابات مباشرة
print(f"الإجمالي: {price * quantity}")  # الإجمالي: 149.97

# استدعاء دوال
name: str = "محمد"
print(f"الاسم بحروف كبيرة: {name.upper()}")  # الاسم بحروف كبيرة: محمد (ملاحظة: upper لا تؤثر على العربية)

# شروط مباشرة (Ternary expressions)
age: int = 15
print(f"الحالة: {'قاصر' if age < 18 else 'بالغ'}")  # الحالة: قاصر

fruits: list[str] = ["تفاح", "موز"]

# إضافة عنصر واحد في النهاية
fruits.append("برتقال")
print(fruits)  # ['تفاح', 'موز', 'برتقال']

# إدراج عنصر في موضع محدد
fruits.insert(1, "عنب")
print(fruits)  # ['تفاح', 'عنب', 'موز', 'برتقال']

# إضافة عدة عناصر دفعة واحدة
fruits.extend(["مانجو", "أناناس"])
print(fruits)  # ['تفاح', 'عنب', 'موز', 'برتقال', 'مانجو', 'أناناس']

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
الفصل السابع: التكرار (Loops)
القسم 7.7: `continue`: تخطّي التكرار الحالي فقط

المصدر: كتاب «بايثون 3.14 — من الصفر إلى الاحتراف»
الملف: 07-011-ex7_7.py
"""

for number in range(1, 11):
    if number % 2 == 0:  # إذا كان زوجيًا
        continue  # تخطّى باقي كود هذا التكرار، انتقل للتالي مباشرة
    print(number)

sentence: str = "التفاح,الموز,البرتقال"

# تقسيم النص إلى قائمة (سنتعلم القوائم بعمق في الفصل الثامن)
fruits: list[str] = sentence.split(",")
print(fruits)  # ['التفاح', 'الموز', 'البرتقال']

# العملية العكسية: دمج قائمة في نص واحد
joined: str = " - ".join(fruits)
print(joined)  # التفاح - الموز - البرتقال

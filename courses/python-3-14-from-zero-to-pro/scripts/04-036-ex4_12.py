# ❌ غير فعّال عند دمج نصوص كثيرة في حلقة (سنتعلم الحلقات في الفصل السابع)
result: str = ""
for i in range(1000):
    result += str(i)  # كل عملية += تُنشئ نصًا جديدًا بالكامل في الذاكرة!

# ✅ أكثر كفاءة (سنطبقها عمليًا لاحقًا)
parts: list[str] = [str(i) for i in range(1000)]
result: str = "".join(parts)

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
الفصل الرابع: التعامل مع النصوص (Strings)
القسم 4.4: f-strings: الطريقة الحديثة والوحيدة التي يجب أن تتعلمها

المصدر: كتاب «بايثون 3.14 — من الصفر إلى الاحتراف»
الملف: 04-009-ex4_4.py
"""

price: float = 1234.5678

# تحديد عدد الخانات العشرية
print(f"{price:.2f}")  # 1234.57 (تقريب لخانتين عشريتين)

# إضافة فاصلة آلاف
print(f"{price:,.2f}")  # 1,234.57

# عرض كنسبة مئوية
ratio: float = 0.856
print(f"{ratio:.1%}")  # 85.6%

# محاذاة النص (مفيد جدًا للجداول في الطرفية)
name: str = "محمد"
print(f"[{name:>10}]")   # [     محمد] (محاذاة يمين، عرض 10)
print(f"[{name:<10}]")   # [محمد     ] (محاذاة يسار، عرض 10)
print(f"[{name:^10}]")   # [   محمد   ] (محاذاة وسط، عرض 10)

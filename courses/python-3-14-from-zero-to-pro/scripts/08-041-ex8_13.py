numbers: list[int] = [1, 2, 3, 4, 5]

# ❌ خطر! نتائج غير متوقعة
for number in numbers:
    if number % 2 == 0:
        numbers.remove(number)  # تعديل القائمة أثناء المرور عليها!

print(numbers)  # [1, 3, 5] لكن بطريقة غير موثوقة ومحتملة الخطأ

df = pd.DataFrame({
    "التاريخ": ["2024-01-15", "2024-02-20", "2024-03-10"],
    "المبيعات": [1000, 1500, 1200],
})

# تحويل النص إلى تاريخ حقيقي
df["التاريخ"] = pd.to_datetime(df["التاريخ"])

# استخراج معلومات من التاريخ

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
الفصل الرابع: التعامل مع النصوص (Strings)
القسم 4.4: f-strings: الطريقة الحديثة والوحيدة التي يجب أن تتعلمها

المصدر: كتاب «بايثون 3.14 — من الصفر إلى الاحتراف»
الملف: 04-006-name.py
"""

name = "سارة"
age = 28

# الطريقة 1: % formatting (قديمة جدًا، نادرًا ما تُستخدم اليوم)
print("اسمي %s وعمري %d" % (name, age))

# الطريقة 2: .format() (كانت شائعة، أصبحت أقل استخدامًا)
print("اسمي {} وعمري {}".format(name, age))

# الطريقة 3: f-strings (الحديثة - من Python 3.6+)
print(f"اسمي {name} وعمري {age}")

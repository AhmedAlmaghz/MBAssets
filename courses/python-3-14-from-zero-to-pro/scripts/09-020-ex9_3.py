# فحص العلاقات بين المجموعات
a = {1, 2, 3}
b = {1, 2, 3, 4, 5}

print(a.issubset(b))     # True -- a مجموعة جزئية من b
print(b.issuperset(a))   # True -- b تحتوي كل عناصر a
print(a.isdisjoint({9, 10}))  # True -- لا يوجد أي عنصر مشترك

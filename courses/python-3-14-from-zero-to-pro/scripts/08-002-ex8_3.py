fruits: list[str] = ["تفاح", "موز", "برتقال", "عنب"]

print(fruits[0])    # تفاح  (أول عنصر)
print(fruits[-1])   # عنب   (آخر عنصر)
print(fruits[1:3])  # ['موز', 'برتقال']  (تقطيع - نفس منطق النصوص)

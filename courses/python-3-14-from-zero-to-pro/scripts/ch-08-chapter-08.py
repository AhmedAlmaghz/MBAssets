def display_menu() -> None:
    print("\n" + "=" * 35)
    print("📋  قائمة المهام")
    print("=" * 35)
    print("1. إضافة مهمة جديدة")
    print("2. عرض كل المهام")
    print("3. حذف مهمة")
    print("4. إنهاء البرنامج")
    print("=" * 35)


"""
الفصل الرابع: التعامل مع النصوص (Strings)
القسم 4.6: التقطيع (Slicing): استخراج جزء من النص

المصدر: كتاب «بايثون 3.14 — من الصفر إلى الاحتراف»
الملف: 04-016-ex4_6.py
"""

text: str = "البرمجة ممتعة"

print(text[0:8])    # البرمجة  (من الفهرس 0 حتى 7، الفهرس 8 غير مُضمَّن)
print(text[9:])     # ممتعة    (من الفهرس 9 حتى النهاية)
print(text[:8])     # البرمجة  (من البداية حتى الفهرس 7)
print(text[:])      # البرمجة ممتعة  (نسخة كاملة من النص)
